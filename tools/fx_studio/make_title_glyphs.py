"""Writes title_glyphs.js: the game's title as pixel bitmaps.

    python tools/fx_studio/make_title_glyphs.py

Each character of TEXT is drawn once with the project's 12-pixel font; the
title effect (effects.js) builds every lit pixel as one falling block. Needs
Pillow. Rerun only when the title or the font changes.
"""
import json
import os

from PIL import Image, ImageDraw, ImageFont

TEXT = "俄罗斯方块"
SIZE = 12
HERE = os.path.dirname(os.path.abspath(__file__))
FONT = os.path.join(HERE, "..", "..", "assets", "fonts", "fusion-pixel-12px-proportional-zh_hans.ttf")


def main():
    font = ImageFont.truetype(FONT, SIZE)
    # Drawn with room to spare, then cut to the rows the characters really use:
    # the font sits a few pixels down from where the text is placed.
    canvas = SIZE * 2
    images = []
    top, bottom = canvas, 0
    for char in TEXT:
        image = Image.new("L", (canvas, canvas), 0)
        ImageDraw.Draw(image).text((0, 0), char, fill=255, font=font)
        box = image.getbbox()
        top, bottom = min(top, box[1]), max(bottom, box[3])
        images.append(image)
    if bottom - top > SIZE:
        raise SystemExit("the characters are taller than %d pixels" % SIZE)
    # Bottom-aligned in the SIZE-row cell.
    first = bottom - SIZE
    glyphs = []
    for char, image in zip(TEXT, images):
        rows = ["".join("#" if 0 <= y and image.getpixel((x, y)) >= 128 else "." for x in range(SIZE)) for y in range(first, bottom)]
        glyphs.append(rows)
        print(char)
        print(chr(10).join(rows))
    data = {"text": TEXT, "size": SIZE, "glyphs": glyphs}
    with open(os.path.join(HERE, "title_glyphs.js"), "w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by make_title_glyphs.py - the title as 12-pixel bitmaps.\n")
        out.write("(function (root) {\n\tconst data = %s;\n" % json.dumps(data, ensure_ascii=False))
        out.write("\tif (root.PixelFX) root.PixelFX.titleGlyphs = data;\n")
        out.write("\tif (typeof module !== 'undefined' && module.exports) module.exports = data;\n")
        out.write("})(typeof globalThis !== 'undefined' ? globalThis : this);\n")


if __name__ == "__main__":
    main()
